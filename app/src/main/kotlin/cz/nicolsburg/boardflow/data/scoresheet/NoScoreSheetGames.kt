/** Why a game gets no score sheet and is never offered an AI draft. */
enum class NoSheetReason(val message: String) {
    COOPERATIVE("Everyone wins or loses together, so there are no scores to add up"),
    DURING_PLAY("Points are scored during play, so the final score is already on the board"),
